# Creates data/childcare/facilities_SAMPLE.csv: a PLACEHOLDER list of fake
# child care facilities scattered at random inside Forsyth County, so the
# childcare module can be built and tested before real facility data is
# obtained. Nothing in this file is a real facility.
#
# Run once from the project folder:  Rscript scripts/make_sample_facilities.R

set.seed(20261123)
options(tigris_use_cache = TRUE)
county <- tigris::counties(state = "37", year = 2024, cb = TRUE, progress_bar = FALSE)
county <- county[county$GEOID == "37067", ]
county <- sf::st_transform(county, 32119)

n_center <- 95
n_home <- 55
pts <- sf::st_transform(sf::st_sample(county, n_center + n_home), 4326)
xy <- sf::st_coordinates(pts)
type <- c(rep("Center", n_center), rep("Family Child Care Home", n_home))
cap <- ifelse(type == "Center", sample(seq(20, 160, by = 5), n_center + n_home, replace = TRUE),
              sample(5:12, n_center + n_home, replace = TRUE))
star <- sample(c(3, 4, 5, NA), n_center + n_home, replace = TRUE, prob = c(0.15, 0.3, 0.5, 0.05))

out <- data.frame(
  license_number = sprintf("SAMPLE-%03d", seq_along(type)),
  facility_name = sprintf("SAMPLE Facility %03d (not real)", seq_along(type)),
  facility_type = type,
  address = "Synthetic location (not a real address)",
  city = "Forsyth County",
  zip = NA,
  latitude = round(xy[, 2], 5),
  longitude = round(xy[, 1], 5),
  licensed_capacity = cap,
  star_rating = star,
  serves_infants = sample(c(TRUE, FALSE), length(type), replace = TRUE, prob = c(0.6, 0.4)),
  source = "SAMPLE placeholder generated by scripts/make_sample_facilities.R",
  as_of_date = "2026-11-23"
)
dir.create("data/childcare", recursive = TRUE, showWarnings = FALSE)
con <- file("data/childcare/facilities_SAMPLE.csv", "w")
writeLines("# SAMPLE PLACEHOLDER DATA: these are NOT real child care facilities. Random points inside Forsyth County for testing only. Replace with real data (see data/childcare/README.md).", con)
close(con)
readr::write_csv(out, "data/childcare/facilities_SAMPLE.csv", append = TRUE, col_names = TRUE, na = "")
message("Wrote ", nrow(out), " sample facilities.")
